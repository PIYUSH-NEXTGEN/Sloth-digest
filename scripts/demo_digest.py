#!/usr/bin/env python3
"""Render a digest for one synthetic chat through the real pipeline.

Demo flow (agent.md B3.2): a 500-message overnight chat becomes a ~10-line
digest. Deterministic end-to-end: the chat is generated by
scripts/gen_synthetic_chats.py, the model step is ScriptedPipelineClient --
the same false-free stand-in used by eval/run_eval.py -- so the demo runs
anywhere, offline, with zero API calls or Ollama needed.

Usage:
    uv run --project backend python scripts/demo_digest.py \
        --chat data/demo/chat.txt [--expected data/demo/expected.json] \
        [--out data/demo/digest.md]
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend"))


def _load_eval_harness():
    """Reuse ScriptedPipelineClient from eval/run_eval.py (not a package)."""
    path = REPO_ROOT / "eval" / "run_eval.py"
    spec = importlib.util.spec_from_file_location("eval_run_eval", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--chat",
        type=Path,
        default=REPO_ROOT / "eval" / "datasets" / "base" / "chat.txt",
    )
    parser.add_argument("--expected", type=Path, default=None)
    parser.add_argument(
        "--out", type=Path, default=REPO_ROOT / "data" / "demo" / "digest.md"
    )
    args = parser.parse_args()

    expected_path = args.expected or args.chat.parent / "expected.json"
    expected = json.loads(expected_path.read_text(encoding="utf-8"))

    harness = _load_eval_harness()
    with tempfile.TemporaryDirectory(prefix="sloth-demo-") as tmp:
        os.environ["SLOTH_DB_PATH"] = os.path.join(tmp, "sloth.db")
        os.environ["SLOTH_DROP_FOLDER"] = str(Path(tmp) / "drop")
        Path(tmp, "drop").mkdir()
        harness.get_settings.cache_clear()
        try:
            digest = _render(args.chat, expected, harness)
        finally:
            harness.get_settings.cache_clear()

    digest_lines, digest_markdown = _format(digest)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(digest_markdown, encoding="utf-8")
    print(digest_lines)
    print(f"[wrote {args.out}]")
    return 0


def _render(chat_path: Path, expected: dict, harness) -> dict:
    from app.main import create_app
    from fastapi.testclient import TestClient

    app = create_app(
        llm=harness.ScriptedPipelineClient(expected.get("planted_facts", []))
    )
    payload = chat_path.read_bytes()
    fields: dict = {}
    if "conversation_name" in expected:
        fields["conversation_name"] = expected["conversation_name"]
    with TestClient(app) as client:
        response = client.post(
            "/ingest/file", files={"file": (chat_path.name, payload)}, data=fields
        )
        assert response.status_code == 200, response.text
        conversation_id = response.json()["conversation_id"]
        put = client.put(
            "/settings",
            json={
                "user_names": expected.get("user_identifiers", ["You"]),
                "vip_people": [],
                "keywords": [],
                "digest_time": "06:00",
                "model": "scripted",
            },
        )
        assert put.status_code == 200, put.text
        run = client.post(
            "/digest/run",
            json={
                "since": expected["start"][:10] + "T00:00:00Z",
                "conversation_ids": [conversation_id],
            },
        )
        assert run.status_code == 202, run.text
        return client.get(f"/digest/{run.json()['digest_id']}").json()


def _collapse_same_text(items: list[dict]) -> list[dict]:
    """Group needs-you items that carry the same summary text."""
    clusters: list[dict] = []
    seen: dict[str, dict] = {}
    for item in items:
        summary = item.get("summary") or ""
        if summary in seen:
            seen[summary]["count"] += 1
            continue
        cluster = {"first": item, "count": 1}
        clusters.append(cluster)
        seen[summary] = cluster
    return clusters


def _format(digest: dict) -> tuple[str, str]:
    """Return (terminal lines, markdown body) for a Digest payload."""
    lines: list[str] = []
    markdown: list[str] = []
    head = (
        f"SlothDigest digest {digest['id']} | model {digest['model']} | "
        f"window {digest['window']['start']} .. {digest['window']['end']}"
    )
    lines.append(head)
    markdown.append(f"# {head}\n")
    for group in digest["groups"]:
        lines.append("")
        lines.append(f"# {group['name']} ({group['platform']}, {group['message_count']} messages)")
        markdown.append(f"## {group['name']}")
        markdown.append(f"*{group['tldr']}*")
        lines.append(f"TL;DR: {group['tldr']}")
        if group["needs_you"]:
            lines.append("NEEDS YOU:")
            markdown.append("\n**Needs you**\n")
            collapsed = _collapse_same_text(group["needs_you"])
            for cluster in collapsed:
                item = cluster["first"]
                suffix = "" if cluster["count"] == 1 else f" (+{cluster['count'] - 1} identical by others)"
                entry = f"- {item['from']}: {item['summary']} ({item['reason']}){suffix}"
                lines.append(entry)
                markdown.append(entry)
                if item.get("suggested_reply"):
                    lines.append(f"  draft: {item['suggested_reply']}")
        for section, key in (("DECISIONS", "decisions"), ("DEADLINES", "deadlines")):
            if group.get(key):
                lines.append(f"{section}:")
                markdown.append(f"\n**{section.title()}**\n")
                for entry in group[key]:
                    when = entry.get("when")
                    text = f"- {entry['text']}" + (f" (by {when})" if when else "")
                    lines.append(text)
                    markdown.append(text)
        if group["by_person"]:
            lines.append("BY PERSON:")
            markdown.append("\n**By person**\n")
            for person in group["by_person"]:
                bullet = f"- {person['name']}: {'; '.join(person['points'])}"
                lines.append(bullet)
                markdown.append(bullet)
        lines.append(
            f"Skipped {group['skipped_count']} low-value messages of banter."
        )
    return "\n".join(lines), "\n".join(markdown) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
